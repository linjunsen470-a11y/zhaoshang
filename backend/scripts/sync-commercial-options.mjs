import { readFile, writeFile } from 'node:fs/promises'

const options = JSON.parse(await readFile(new URL('../collections/shared/commercialOptions.json', import.meta.url), 'utf8'))
await writeFile(new URL('../../mp/config/commercial.js', import.meta.url), `// Generated by backend/scripts/sync-commercial-options.mjs.\nmodule.exports = ${JSON.stringify(options, null, 2)};\n`)
console.log('Mini-program commercial options synchronized.')
